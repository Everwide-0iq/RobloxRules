type LocalizedDisplay<Value> = Value extends string
  ? string
  : Value extends readonly (infer Item)[]
    ? readonly LocalizedDisplay<Item>[]
    : Value extends object
      ? { readonly [Key in keyof Value]: LocalizedDisplay<Value[Key]> }
      : never;

type CopyMap<Items extends readonly { readonly id: string }[], MetadataKey extends PropertyKey> = {
  readonly [Item in Items[number] as Item['id']]: {
    readonly [Key in Exclude<keyof Item, MetadataKey>]: LocalizedDisplay<Item[Key]>;
  };
};

function mergeById<const Items extends readonly { readonly id: string }[]>(
  items: Items,
  copy: Readonly<Record<NoInfer<Items[number]['id']>, object>>,
): Items[number][] {
  type ItemId = Items[number]['id'];

  return items.map((item) => ({ ...item, ...copy[item.id as ItemId] }));
}

