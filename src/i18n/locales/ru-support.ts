function mergeById<Item extends { readonly id: string }>(
  items: readonly Item[],
  copy: Readonly<Record<string, object>>,
) {
  return items.map((item) => ({ ...item, ...copy[item.id] }));
}

function mergeByIdWithCommon<Item extends { readonly id: string }, Common extends object>(
  items: readonly Item[],
  copy: Readonly<Record<string, object>>,
  common: Common,
) {
  return items.map((item) => ({ ...item, ...copy[item.id], ...common }));
}

function mergeDisplayCopy<Item extends object, Copy extends object>(item: Item, copy: Copy) {
  return { ...item, ...copy };
}

