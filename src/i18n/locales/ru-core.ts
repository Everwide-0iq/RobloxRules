function mergeById<
  Item extends { readonly id: string },
  Copy extends Readonly<Record<Item['id'], object>>,
>(items: readonly Item[], copy: Copy) {
  return items.map((item) => {
    const id: Item['id'] = item.id;
    return { ...item, ...copy[id] };
  });
}

